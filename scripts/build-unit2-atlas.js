#!/usr/bin/env node
'use strict';
const fs=require('fs'),path=require('path'),vm=require('vm');
const root=path.resolve(__dirname,'..');
const content=require('./lib/unit2-atlas-content');
const contract=require('./lib/ced-unit2-contract');
function lessonFor(topic){
 const document={querySelector:s=>s.startsWith('link[')?{}:null};
 const context=vm.createContext({window:{},document});
 const read=f=>fs.readFileSync(path.join(root,'assets/data',f),'utf8');
 vm.runInContext(read(contract.topics[topic].file),context);
 vm.runInContext(read(`lesson-${topic.replace('.','-')}-renderer-config.js`),context);
 vm.runInContext(read('ap-practice-units-1-2.js'),context);
 return context.window.BEHISTORICAL_LESSON;
}
const data={unitQuestion:'How did connections across Afro-Eurasia expand, and how did they change societies?',topics:{}};
for(const [id,investigation] of Object.entries(content.topicNotes)){
 const lesson=lessonFor(id);
 data.topics[id]={id,title:investigation.title,focus:investigation.focus,period:investigation.period,
  lesson:contract.topics[id].file.replace(/\.js$/,'.html'),source:lesson.primarySource,
  views:content.topics[id].layers.map((name,i)=>{const v=content.view(id,i);return{name,places:v.places,
   sets:v.sets.map(set=>({...set,detail:content.routeNotes[set.key]}))};})};
}
const file=path.join(root,'assets/data/unit2-network-atlas.js');
const output='// Generated by scripts/build-unit2-atlas.js. Author content in scripts/lib/unit2-atlas-content.js.\nwindow.BH_UNIT2_ATLAS = '+JSON.stringify(data,null,2)+';\n';
if(process.argv.includes('--check')){
 if(!fs.existsSync(file)||fs.readFileSync(file,'utf8')!==output){console.error('Unit 2 atlas data drift. Run node scripts/build-unit2-atlas.js.');process.exit(1);}
 console.log('Unit 2 atlas data matches authored content and canonical lesson sources.');
}else{fs.writeFileSync(file,output);console.log('Built Unit 2 atlas data.');}
