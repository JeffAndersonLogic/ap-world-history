#!/usr/bin/env node
'use strict';
/**
 * build-topic-audit-index.js
 *
 * Writes docs/topic-audits/index.md, the one page that answers "which topics have
 * been audited, and is that audit still true of the topic as it stands today".
 *
 * Generated, never hand-kept. A coverage page someone has to remember to update
 * is the same defect as the audit that had no record: it looks right, and nothing
 * can say when it stopped being right. `--check` fails on drift and runs in the
 * offline suite, so a hand-edit fails the push instead of being silently reverted
 * by the next rebuild.
 *
 * It derives everything from scripts/lib/topic-audit-coverage.js and formats it.
 * It decides nothing of its own.
 *
 *   node scripts/build-topic-audit-index.js          # write
 *   node scripts/build-topic-audit-index.js --check  # fail on drift, write nothing
 */

const fs = require('fs');
const path = require('path');
const cov = require('./lib/topic-audit-coverage.js');

const OUT = path.join(cov.AUDIT_DIR, 'index.md');

const STATE = {
  fresh:            { mark: 'Fresh',   note: 'audited, and nothing has changed since' },
  stale:            { mark: 'Stale',   note: 'the topic changed after its audit' },
  'shared-changed': { mark: 'Review',  note: 'a file shared across the unit changed after its audit' },
  never:            { mark: 'Never',   note: 'no audit record exists' }
};

function render(c) {
  const L = [];
  L.push('# Topic audit coverage');
  L.push('');
  L.push('**Generated by `scripts/build-topic-audit-index.js`. Do not edit by hand.**');
  L.push('Rebuild it with `npm run build:audit-index`; the offline suite fails on drift.');
  L.push('');
  L.push('For what is due *this week*, run `node scripts/check-audit-freshness.js`.');
  L.push('That view depends on today\'s date, so it is deliberately not baked in here:');
  L.push('a generated file carrying it would drift at every midnight.');
  L.push('');
  L.push('One row per topic on the schedule. A row is **Fresh** only when an audit record');
  L.push('exists and nothing in that topic has changed since the audit date, so a topic');
  L.push('audited in September and revised in October reads as Stale rather than done.');
  L.push('');
  L.push('Dates are the school\'s own, in Indiana time. This page is a view, not a');
  L.push('state file: every value on it is derived at build time from the audit records');
  L.push('in this folder, the schedule, and git history.');
  L.push('');

  // NO "taught in the next N days" section here, deliberately.
  //
  // That view depends on today's date, so a generated file carrying it drifts
  // every midnight and `--check` in the push gate would fail on a day passing
  // rather than on anything anyone did. The first draft of this script did carry
  // it, with a comment claiming the output was pinned, which was simply untrue.
  //
  // Every column below is a fact about the repository: an audit record's date, a
  // schedule date, and a git history date. Those move only when someone commits.
  // The live "what is due this week" view belongs to check-audit-freshness.js,
  // which runs nightly and prints it against the real clock.

  L.push('## Every scheduled topic');
  L.push('');
  L.push('| Topic | Green | Silver | Audit state | Last audited | Record |');
  L.push('|---|---|---|---|---|---|');
  for (const r of c.rows) {
    const g = r.days.find(d => d.cohort === 'green');
    const s = r.days.find(d => d.cohort === 'silver');
    L.push(`| ${r.topic} | ${g ? g.date : '-'} | ${s ? s.date : '-'} | ${STATE[r.state].mark} | ${r.audited || '-'} | ${r.record ? '`' + r.record + '`' : '-'} |`);
  }
  L.push('');

  const counts = {};
  for (const r of c.rows) counts[r.state] = (counts[r.state] || 0) + 1;
  L.push('## Totals');
  L.push('');
  L.push('| State | Topics | Meaning |');
  L.push('|---|---|---|');
  for (const k of ['fresh', 'stale', 'shared-changed', 'never']) {
    L.push(`| ${STATE[k].mark} | ${counts[k] || 0} | ${STATE[k].note} |`);
  }
  L.push('');

  L.push('## Is the weekly sweep alive?');
  L.push('');
  if (c.lastSweep) {
    L.push(`Most recent sweep marker: **${c.lastSweep}**, of ${c.sweeps.length} on record.`);
  } else {
    L.push('**No sweep marker exists yet.** The weekly sweep writes one every time it');
    L.push('runs, including on a week with nothing scheduled, so a missing marker means');
    L.push('the automation did not run, never that there was nothing to do.');
  }
  L.push('');
  L.push('`scripts/check-audit-freshness.js` is what fails when that marker goes stale.');
  L.push('It runs nightly rather than in the push gate, because an overdue audit must');
  L.push('never be the thing standing between a broken classroom page and a fix.');
  L.push('');

  if (c.malformed.length) {
    L.push('## Unreadable records');
    L.push('');
    L.push('These files are in this folder and could not be parsed, so they count for');
    L.push('nothing above. That is deliberately loud: a record that silently failed to');
    L.push('parse would make an audited topic read as never audited.');
    L.push('');
    for (const m of c.malformed) L.push(`- \`${m.file}\`: ${m.problems.join('; ')}`);
    L.push('');
  }

  return L.join('\n') + '\n';
}

function main() {
  const check = process.argv.includes('--check');
  // `today` still reaches coverage() because it decides the `upcoming` flag, which
  // render() no longer prints. Nothing clock-dependent survives into the file.
  const c = cov.coverage({ today: cov.schoolToday() });
  const next = render(c);
  const prev = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : null;

  if (check) {
    if (prev === next) { console.log('topic audit index: up to date'); return 0; }
    console.error('topic audit index: DRIFT. docs/topic-audits/index.md does not match the records.');
    console.error('Run: node scripts/build-topic-audit-index.js');
    return 1;
  }
  fs.mkdirSync(cov.AUDIT_DIR, { recursive: true });
  fs.writeFileSync(OUT, next);
  console.log(`topic audit index: wrote docs/topic-audits/index.md (${c.rows.length} topics)`);
  return 0;
}

if (require.main === module) process.exit(main());
module.exports = { render };
