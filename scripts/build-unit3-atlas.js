#!/usr/bin/env node
'use strict';
const fs=require('fs'),path=require('path');
const data=require('./lib/unit3-atlas-content');
const file=path.resolve(__dirname,'../assets/data/unit3-network-atlas.js');
const output='// Generated by scripts/build-unit3-atlas.js.\nwindow.BH_NETWORK_ATLAS = '+JSON.stringify(data,null,2)+';\n';
if(process.argv.includes('--check')){
 if(!fs.existsSync(file)||fs.readFileSync(file,'utf8')!==output){console.error('Unit 3 atlas data drift. Run node scripts/build-unit3-atlas.js.');process.exit(1);}
 console.log('Unit 3 atlas matches reviewed content.');
}else{fs.writeFileSync(file,output);console.log('Built Unit 3 atlas data.');}
