#!/usr/bin/env node
'use strict';
const fs=require('fs'),path=require('path');
for(const unit of [4,5]){
 const data=require('./lib/unit'+unit+'-atlas-content');
 const file=path.resolve(__dirname,'../assets/data/unit'+unit+'-network-atlas.js');
 const output='// Generated by scripts/build-unit45-atlases.js.\nwindow.BH_NETWORK_ATLAS = '+JSON.stringify(data,null,2)+';\n';
 if(process.argv.includes('--check')){
  if(!fs.existsSync(file)||fs.readFileSync(file,'utf8')!==output){console.error('Unit '+unit+' atlas data drift. Run node scripts/build-unit45-atlases.js.');process.exit(1);}
  console.log('Unit '+unit+' atlas matches reviewed content.');
 }else{fs.writeFileSync(file,output);console.log('Built Unit '+unit+' atlas data.');}
}
