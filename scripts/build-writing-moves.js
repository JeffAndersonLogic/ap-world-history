#!/usr/bin/env node
'use strict';

/**
 * Builds everything that comes out of scripts/lib/writing-moves.js, so the
 * lessons and the writing coach can never teach different words:
 *
 *   assets/data/writing-moves.js        what the lesson renderer reads to draw
 *                                       the Writing Move box (student-facing)
 *   docs/yukichi/yukichi-instructions.md  paste into the Yukichi chatbot's
 *                                       instructions field in MagicSchool
 *   docs/yukichi/yukichi-knowledge.md   paste or upload as Yukichi's private
 *                                       reference (never shown to students)
 *
 * The private reference joins each move to the College Board's own wording in
 * scripts/lib/ced-source/free-response.js. Point labels are stripped from the
 * criteria there; the persona tells Yukichi never to speak in points.
 *
 * Rebuild after changing the moves, the persona, or the CED source, then
 * re-paste both Yukichi files into MagicSchool.
 *
 * Usage: node scripts/build-writing-moves.js [--check]
 *   --check  fail on drift without writing (run by the offline suite)
 */

const fs = require('fs');
const path = require('path');
const { MOVES } = require('./lib/writing-moves');
const { YUKICHI_PERSONA } = require('./lib/yukichi-persona');
const CED = require('./lib/ced-source/free-response');

const ROOT = path.join(__dirname, '..');
const CHECK = process.argv.includes('--check');
const GEN = '<!-- GENERATED by scripts/build-writing-moves.js, do not hand-edit. Rebuild: node scripts/build-writing-moves.js -->';

// The student-facing fields, and nothing else: no CED rows, no units, no points.
const STUDENT_FIELDS = ['id', 'name', 'what', 'steps', 'avoid', 'onTheExam'];

const problems = [];

// ── Resolve a move's CED citations ───────────────────────────────────────────

const skillText = {};
for (const s of CED.skills) for (const sub of s.subskills) skillText[sub.code] = { name: s.name, text: sub.text };

function rubricRow(ref) {
  const [exam, category] = ref.split(':');
  const rows = exam === 'dbq' ? CED.dbqRubric : exam === 'leq' ? CED.leqRubric : null;
  return rows ? rows.find(r => r.category === category) : null;
}

function resolveRef(ref) {
  if (ref === 'taskVerbs') return { label: `Task verbs (CED p. ${CED.taskVerbs.page})`, lines: Object.entries(CED.taskVerbs).filter(([k]) => k !== 'page').map(([k, v]) => `**${k}:** ${v}`) };
  if (ref === 'shortAnswerNotes') return { label: `Short-answer scoring notes (CED p. ${CED.shortAnswerNotes.page})`, lines: CED.shortAnswerNotes.notes };
  if (ref === 'shortAnswer') return { label: `The short-answer section (CED p. ${CED.sections.shortAnswer.page})`, lines: [CED.sections.shortAnswer.text] };
  const row = rubricRow(ref);
  if (!row) return null;
  const exam = ref.startsWith('dbq') ? 'Document-based question' : 'Long essay question';
  // "1 pt: X OR 2 pts: Y" becomes two plain lines; the point labels never leave this file.
  const criteria = row.criterion.split(/\s*OR\s+\d+\s*pts?:\s*/).map(s => s.replace(/^\d+\s*pts?:\s*/, '').trim());
  return {
    label: `${exam}, ${row.category} (CED p. ${row.page})`,
    lines: [...criteria.map(c => `Criterion: ${c}`), `Decision rules: ${row.decisionRules}`]
  };
}

for (const m of MOVES) {
  for (const code of m.ced.skills) if (!skillText[code]) problems.push(`${m.id}: cites skill ${code}, which the CED does not have`);
  for (const ref of m.ced.rows) if (!resolveRef(ref)) problems.push(`${m.id}: cites rubric row "${ref}", which the CED source does not have`);
}

// ── The three files ──────────────────────────────────────────────────────────

function browserData() {
  const moves = {};
  for (const m of MOVES) moves[m.id] = Object.fromEntries(STUDENT_FIELDS.map(k => [k, m[k]]));
  return [
    '// GENERATED by scripts/build-writing-moves.js from scripts/lib/writing-moves.js.',
    '// Do not hand-edit. Rebuild: node scripts/build-writing-moves.js',
    '// The lesson renderer reads this to draw the Writing Move box in Modules 05 and 08.',
    `window.BEHISTORICAL_WRITING_MOVES = ${JSON.stringify(moves, null, 2)};`,
    ''
  ].join('\n');
}

const plain = s => String(s).replace(/<\/?strong>/g, '**').replace(/<[^>]+>/g, '');

function instructionsDoc() {
  return [
    GEN, '',
    YUKICHI_PERSONA.trim(), '',
    '## The moves, by their class names', '',
    ...MOVES.map(m => `- ${m.name}`), ''
  ].join('\n');
}

function knowledgeDoc() {
  const out = [
    GEN, '',
    '# Yukichi private reference',
    '',
    'Private reference for the writing coach. Never quote it to a student as a',
    'scoring guide, and never mention points: the College Board wording below is',
    'written for scorers. Use it to decide whether a draft does what a move asks,',
    'then coach in the plain words under each move.',
    '',
    `Source: ${CED.edition}, transcribed ${CED.transcribed}.`,
    '',
    '## General notes the College Board gives readers', '',
    ...CED.rubricNotes.notes.map(n => `- ${n}`), ''
  ];
  for (const m of MOVES) {
    out.push(`## ${m.name}`, '');
    out.push(plain(m.what), '');
    out.push('Steps the class teaches:', '');
    m.steps.forEach((s, i) => out.push(`${i + 1}. ${plain(s)}`));
    out.push('', 'Mistakes to watch for:', '');
    m.avoid.forEach(a => out.push(`- ${plain(a)}`));
    out.push('', `On the exam: ${plain(m.onTheExam)}`, '');
    out.push('College Board wording:', '');
    for (const code of m.ced.skills) out.push(`- Skill ${code} (${skillText[code].name}): ${skillText[code].text}`);
    for (const ref of m.ced.rows) {
      const r = resolveRef(ref);
      out.push(`- ${r.label}`);
      r.lines.forEach(l => out.push(`  - ${l}`));
    }
    out.push('');
  }
  return out.join('\n');
}

const files = {
  'assets/data/writing-moves.js': browserData(),
  'docs/yukichi/yukichi-instructions.md': instructionsDoc(),
  'docs/yukichi/yukichi-knowledge.md': knowledgeDoc()
};

// ── Write or check ───────────────────────────────────────────────────────────

if (problems.length) {
  console.error(`${problems.length} problem(s):`);
  problems.forEach(p => console.error('  ' + p));
  process.exit(1);
}

let drift = 0;
for (const [rel, body] of Object.entries(files)) {
  const dest = path.join(ROOT, rel);
  const before = fs.existsSync(dest) ? fs.readFileSync(dest, 'utf8') : null;
  if (before === body) continue;
  if (CHECK) { drift++; console.error(`DRIFT ${rel}`); continue; }
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.writeFileSync(dest, body);
  console.log(`wrote ${rel}`);
}

const kb = n => (n / 1024).toFixed(1) + ' KB';
console.log(`${MOVES.length} moves | instructions ${kb(files['docs/yukichi/yukichi-instructions.md'].length)} | reference ${kb(files['docs/yukichi/yukichi-knowledge.md'].length)}`);
if (CHECK && drift) {
  console.error(`\n${drift} file(s) drifted. Run: node scripts/build-writing-moves.js`);
  process.exit(1);
}

module.exports = { STUDENT_FIELDS };
