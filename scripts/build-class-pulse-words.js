#!/usr/bin/env node
/**
 * build-class-pulse-words.js
 *
 * Writes teacher/data/class-pulse-course-words.js: every capitalized word the course
 * itself uses as a name (Akbar, Malacca, Zheng, Tokugawa), from the skills map, the CED
 * source files, the First & 10 and deep reading content, the lesson data, the teaching
 * decks and the Class Pulse rubrics.
 *
 * Class Pulse's check before copying (teacher/class-pulse-handoff.js) flags a
 * capitalized word in a student's answer that the course never uses, because it may be
 * a person's name. This list is how it tells "Akbar" from "Jayden". A word counts only
 * where the course writes it capitalized in mid-sentence, so ordinary words that open a
 * sentence ("Grace", "Will") never make a student's name look like course vocabulary.
 *
 * A stale list only means more flags, never fewer, so it is not a drift check in the
 * gate. Rebuild after adding a unit or a batch of readings:
 *   node scripts/build-class-pulse-words.js          write the file
 *   node scripts/build-class-pulse-words.js --check  exit 1 if it would change
 */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'teacher', 'data', 'class-pulse-course-words.js');
const files = ['assets/data/skills-map.js', 'scripts/lib/f10-content.js', 'scripts/lib/foundations-f10-content.js', 'teacher/data/class-pulse-rubrics.js'];
// Authored course text only. Never a Class Pulse answer set: those are what gets checked.
const SOURCES = [
  ['scripts/lib/ced-source', /\.js$/], ['scripts/lib/reading-content', /\.js$/], ['scripts/lib/deep-reading-content', /\.js$/],
  ['assets/data', /^lesson-.*\.js$/], ['teacher/data', /^topic-.*-teaching-base\.js$/]
];
for (const [dir, want] of SOURCES) {
  for (const f of fs.readdirSync(path.join(ROOT, dir)).filter(f => want.test(f) && !/renderer-config/.test(f)).sort()) files.push(dir + '/' + f);
}

const words = new Set();
for (const f of files) {
  // Tags and entities come out first so "<span class" or "&amp;" never pass for prose.
  const text = fs.readFileSync(path.join(ROOT, f), 'utf8').replace(/<[^>]*>/g, ' ').replace(/&[a-z]+;/g, ' ');
  for (const m of text.matchAll(/(?<=[^.!?:"'(\[\s]\s+)[A-Z][a-z]+/g)) words.add(m[0].toLowerCase());
}
const list = [...words].sort();
const body = `/* GENERATED by scripts/build-class-pulse-words.js. Do not edit by hand.
 * Capitalized words the course uses as names, lowercased: ${list.length} words from
 * ${files.length} source files. Class Pulse's check before copying uses it to tell a
 * history name from a possible student name. */
(function (root, factory) {
  const api = factory();
  if (typeof module === 'object' && module.exports) module.exports = api;
  else root.BHClassPulseCourseWords = api;
})(typeof globalThis !== 'undefined' ? globalThis : this, function () {
  'use strict';
  return { words: ${JSON.stringify(list)} };
});
`;
if (process.argv.includes('--check')) {
  const same = fs.existsSync(OUT) && fs.readFileSync(OUT, 'utf8') === body;
  console.log(same ? 'class-pulse-course-words.js is current' : 'class-pulse-course-words.js would change; run node scripts/build-class-pulse-words.js');
  process.exit(same ? 0 : 1);
}
fs.writeFileSync(OUT, body);
console.log('wrote', path.relative(ROOT, OUT), list.length, 'words from', files.length, 'files');
