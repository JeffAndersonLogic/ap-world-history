#!/usr/bin/env node
'use strict';
//
// build-inline-fonts.js
//
// Generates assets/fonts/behistorical-fonts-inline.css: the site's three
// typefaces as @font-face rules with the woff2 payload embedded as data URIs.
//
// The Canvas packets cannot link to fonts.googleapis.com, they have to render
// correctly on a filtered network with no outbound access at all. Embedding is
// the only way to keep Cinzel, Libre Baskerville, and Montserrat, and without
// them the packets fall back to Georgia and stop looking like the site.
//
// Only the `latin` subset is kept. The course is in English and latin-ext,
// cyrillic, and vietnamese would roughly triple the payload.
//
// Needs network access to Google Fonts. The output is checked in, so the packet
// build itself stays offline. Re-run only when the site's font stack changes.
//
// Run: node scripts/build-inline-fonts.js

const fs = require('fs');
const path = require('path');

const OUT = path.join(__dirname, '..', 'assets', 'fonts', 'behistorical-fonts-inline.css');

// Variable-weight ranges cover every weight the shell and the readings ask for
// (Cinzel 400-900, Montserrat 400-900) in a single file per family.
const CSS_URL = 'https://fonts.googleapis.com/css2'
  + '?family=Cinzel:wght@400..900'
  + '&family=Libre+Baskerville:ital,wght@0,400;0,700;1,400'
  + '&family=Montserrat:wght@100..900'
  + '&display=swap';

// Google serves woff2 and variable fonts only to browsers it recognises.
const UA = 'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36';

async function get(url, binary) {
  const res = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error(`${res.status} ${res.statusText} for ${url}`);
  return binary ? Buffer.from(await res.arrayBuffer()) : res.text();
}

// Splits the stylesheet into @font-face blocks, each preceded by a /* subset */
// comment, and keeps only the latin ones.
function latinBlocks(css) {
  const blocks = [];
  const re = /\/\*\s*([a-z-]+)\s*\*\/\s*(@font-face\s*\{[^}]*\})/g;
  let m;
  while ((m = re.exec(css)) !== null) {
    if (m[1] === 'latin') blocks.push(m[2]);
  }
  return blocks;
}

(async () => {
  const css = await get(CSS_URL, false);
  const blocks = latinBlocks(css);
  if (!blocks.length) throw new Error('no latin @font-face blocks found, did the Google Fonts response format change?');

  const cache = new Map();
  let total = 0;
  const out = [];

  for (const block of blocks) {
    const urlMatch = block.match(/url\((https:\/\/fonts\.gstatic\.com\/[^)]+)\)/);
    if (!urlMatch) continue;
    const src = urlMatch[1];
    if (!cache.has(src)) {
      const buf = await get(src, true);
      total += buf.length;
      cache.set(src, `data:font/woff2;base64,${buf.toString('base64')}`);
    }
    out.push(block
      .replace(/url\(https:\/\/fonts\.gstatic\.com\/[^)]+\)/, `url(${cache.get(src)})`)
      // unicode-range is pointless once the non-latin subsets are gone, and
      // dropping it avoids a browser deciding it needs a subset that is absent.
      .replace(/\s*unicode-range:[^;]+;/, '')
      .replace(/\s+/g, ' ')
      .trim());
  }

  const header = '/* Generated by scripts/build-inline-fonts.js. Do not edit by hand. */\n';
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, header + out.join('\n') + '\n');

  console.log(`${out.length} @font-face rules, ${cache.size} woff2 files, ${Math.round(total / 1024)} KB raw`);
  console.log(`wrote assets/fonts/behistorical-fonts-inline.css (${Math.round(fs.statSync(OUT).size / 1024)} KB)`);
})().catch(e => { console.error('FAILED: ' + e.message); process.exit(1); });
