#!/usr/bin/env node
/**
 * build-skills-lens.js
 *
 * Inlines the shared libraries into teacher/skills-lens.html.
 *
 * The Lens is one file a teacher downloads and double-clicks. No build step at
 * their end, no npm, no CDN, and a Content-Security-Policy of
 * `default-src 'none'` that forbids fetching anything anyway. So the code it
 * needs has to be physically inside it.
 *
 * That is a copy, and a copy is the thing this repository keeps getting bitten
 * by. The Lens already carried a hand-copied `squashName` with a comment
 * admitting the hazard in as many words. The answer is not to avoid copying, it
 * is to make the copy generated and checked: this script writes it, and
 * validate.js fails the build the moment the inlined bytes drift from the
 * source. Hand-editing anything between the sentinels is the one thing not to do.
 *
 * Two libraries go in:
 *   scripts/lib/canvas-parse-core.js  the parser, shared with the CLI so both
 *                                     doors give the same answer
 *   scripts/lib/canvas-zip.js         reads the Canvas zip with no dependency
 *
 * The generated skills map is inlined by scripts/build-skills-map.js and is not
 * touched here.
 *
 * Usage:
 *   node scripts/build-skills-lens.js [--check]
 *
 *   --check   exit 1 if the file is out of date, write nothing. This is what
 *             validate.js runs.
 */

'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const LENS = path.join(ROOT, 'teacher', 'skills-lens.html');
const CHECK = process.argv.includes('--check');

const LIBS = [
  'scripts/lib/canvas-parse-core.js',
  'scripts/lib/canvas-zip.js'
];

const OPEN = '<!-- BEGIN INLINED LIBS, generated by scripts/build-skills-lens.js -->';
const CLOSE = '<!-- END INLINED LIBS -->';

function block() {
  const parts = LIBS.map(rel => {
    const src = fs.readFileSync(path.join(ROOT, rel), 'utf8');
    // A closing script tag inside a string literal would end the block early.
    // Nothing in these files has one today; this is here so that stays true
    // without anyone having to remember it.
    if (/<\/script/i.test(src)) {
      throw new Error(`${rel} contains a </script sequence, which cannot be inlined verbatim`);
    }
    return `<script>\n/* ${rel}\n   Generated copy. Edit the source and run: node scripts/build-skills-lens.js */\n${src}</script>`;
  });
  return [OPEN].concat(parts).concat([CLOSE]).join('\n');
}

function main() {
  const html = fs.readFileSync(LENS, 'utf8');
  const wanted = block();

  const start = html.indexOf(OPEN);
  const end = html.indexOf(CLOSE);
  if (start === -1 || end === -1) {
    console.error(`teacher/skills-lens.html has no inline-libs sentinels.`);
    console.error(`Add these two lines before the main application <script>:`);
    console.error(`  ${OPEN}`);
    console.error(`  ${CLOSE}`);
    process.exit(2);
  }

  const current = html.slice(start, end + CLOSE.length);
  if (current === wanted) {
    console.log('  teacher/skills-lens.html is up to date.');
    return;
  }

  if (CHECK) {
    console.error('  teacher/skills-lens.html is STALE.');
    console.error('  Its inlined copy of the shared libraries no longer matches the source.');
    console.error('  Run: node scripts/build-skills-lens.js');
    process.exit(1);
  }

  const out = html.slice(0, start) + wanted + html.slice(end + CLOSE.length);
  fs.writeFileSync(LENS, out, 'utf8');
  const kb = n => (n / 1024).toFixed(0) + 'KB';
  console.log(`  Inlined ${LIBS.length} libraries into teacher/skills-lens.html`);
  LIBS.forEach(rel => console.log(`    ${rel.padEnd(38)} ${kb(fs.statSync(path.join(ROOT, rel)).size)}`));
  console.log(`  File is now ${kb(out.length)}`);
}

if (require.main === module) main();
module.exports = { OPEN, CLOSE, LIBS };
