#!/usr/bin/env node
/**
 * wire-beintheroom-coach-prompt.js
 *
 * Normalizes what a BeInTheRoom scenario pastes into Socrates.
 *
 * WHY THIS EXISTS
 *
 * Socrates' persona says the pasted block is authoritative over anything he
 * remembers. That is what lets one bot serve 77 topics, and it is also why a
 * paste can quietly overwrite him. Two things were doing exactly that in every
 * hand-authored scenario:
 *
 *   1. The paste opened "You are the BeInTheRoom Historical Thinking Coach for
 *      AP World History", which names a different coach. A student who is
 *      supposed to be building one relationship with Socrates across nine units
 *      was talking to an unnamed second bot in the one module where the coach is
 *      most present.
 *
 *   2. The paste said "Ask me one question at a time", which is version 1 of the
 *      persona restated inside the student's own message. That rule was removed
 *      from the checkpoint paste on 2026-08-29, for the reason written at the
 *      bottom of assets/js/behistorical-coach-prompt.js: the persona treats the
 *      paste as authoritative, so every paste reinstated the serial questioning
 *      the version 2 retune exists to relax, in the place the persona says wins.
 *      The checkpoint path was fixed. The scenarios were not, so BeInTheRoom has
 *      been running the persona students complained about ever since.
 *
 * On top of both, every scenario closed with a six-stage coaching walk. The
 * persona defers to scenario-authored stages on purpose ("When a paste sets out
 * its own coaching stages, follow those stages"), so six stages at one question
 * each made BeInTheRoom the longest conversation in the course. None of the
 * scenarios authored a genuinely bespoke sequence: all of them carried the same
 * template with per-scenario fill, so the walk is replaced with the bounded ask
 * the persona's own budget describes, and the authored fill is preserved.
 *
 * WHAT IS PRESERVED, AND WHY IT MATTERS
 *
 * Two fragments in the old stage list are real authored content rather than
 * boilerplate, and both are carried into the replacement verbatim:
 *
 *   - stage 5's revision target, which on several scenarios names the AP key
 *     concept the argument has to reach ("that connects to the AP key concept:
 *     groups and individuals opposing existing orders");
 *   - stage 6's step-out-of-character question, which is different on every
 *     scenario and is the reflection that actually reaches Canvas.
 *
 * A sweep that dropped either would look successful and would delete teaching.
 * Any file where a fragment cannot be found is reported and left alone rather
 * than rewritten with a generic substitute.
 *
 * WHAT IS SKIPPED
 *
 * The unit-6 and unit-9 scenarios are generated by scripts/build-unit6.js and
 * scripts/build-unit9.js. Editing them here would survive exactly until the next
 * build, so they are skipped by their generated marker and their paste is fixed
 * in the generators instead.
 *
 * Idempotent: a scenario already carrying the new closing is left untouched, so
 * this can be re-run after a new hand-authored scenario is written.
 *
 * Usage:
 *   node scripts/wire-beintheroom-coach-prompt.js [--dry-run]
 */

'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const ROOM = path.join(ROOT, 'beintheroom');
const DRY = process.argv.includes('--dry-run');

// The generated scenarios declare their whole scenario as one object. That is
// the marker, rather than a list of filenames, so a topic added to either
// generator is skipped here the day it lands instead of the day someone
// remembers to add it.
const GENERATED_MARKER = 'var SCENARIO=';

// The sentence that opened every hand-authored paste. Lazy, because the escaped
// flavour of these files has no real newlines and a greedy match would swallow
// the rest of the payload.
const OLD_HEADER = /You are the BeInTheRoom Historical Thinking Coach for AP World History\.[^\n]*?not just name facts\./;

const NEW_HEADER =
  'Socrates, I am in a BeInTheRoom simulation and you are in the room with me. '
  + 'Push me to explain because, not just name facts.';

// Where the old six-stage walk begins. Some scenarios say "Please coach me
// through these stages:", some drop the "Please".
const STAGES_START = /(?:Please\s+)?[Cc]oach me through these stages:/;

// Marks a file this script has already rewritten.
const NEW_MARKER = 'Coach me on one thing:';

// The canonical last line of a paste, byte-identical to what a checkpoint sends
// from assets/js/behistorical-coach-prompt.js. One wording, so the two surfaces
// cannot drift into asking Socrates for different things.
const CANONICAL_ASK = 'Give me one thing to work on at a time. Do not write my final answer for me.';

// A scenario whose stage list is genuinely its own teaching sequence keeps it.
// The persona defers to scenario-authored stages deliberately, so the only
// things fixed on these are the two that overwrite Socrates: a paste that names
// some other coach, and a paste that restates version 1 of the one-ask rule.
// Topic 9.3 is the case this exists for: its stages name historical
// responsibility, the ENV thematic focus, and the 9.2 to 9.3 bridge, which is a
// sequence about the history rather than a template with the topic dropped in.
const BESPOKE_FIXES = [
  [/Please act as my BeHistorical AI Coach\. Use the/g,
    'Socrates, I am in a BeInTheRoom simulation and you are in the room with me. Work through the'],
  [/Ask me ONE question at a time\. Do not write my answer for me\./g, CANONICAL_ASK],
  [/Ask me one question at a time\. Do not write my answer for me\./g, CANONICAL_ASK]
];

function walk(dir, out) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, out);
    else if (entry.isFile() && entry.name.endsWith('.html') && entry.name !== 'index.html') out.push(full);
  }
  return out;
}

/**
 * A scenario is written either with real newlines inside a template literal or
 * minified onto one line with escaped \n sequences. The replacement has to match
 * whichever the file uses, or the paste arrives as one unreadable paragraph.
 */
function newlineFlavour(block) {
  return block.includes('\\n') ? '\\n' : '\n';
}

/**
 * A preserved fragment goes back inside the literal it came from, so a scenario
 * that says "China's communist revolution" would close a single-quoted payload
 * early and leave the file unparseable.
 */
function escapeForLiteral(text, delim) {
  return delim === '`' ? text : text.split(delim).join(`\\${delim}`);
}

/**
 * Which character closes the string literal the paste lives in.
 *
 * This has to be derived rather than guessed. Scenario prose is full of
 * apostrophes ("Attlee's cabinet", "China's communist revolution"), so treating
 * every ' as a terminator truncates the block mid-sentence, and it does it
 * silently: the sweep still writes a file, and the paste it writes has lost the
 * step-out-of-character question. The nearest preceding assignment is what
 * actually opened the literal, so that is what decides.
 */
function payloadDelimiter(src, start) {
  const before = src.slice(0, start);
  const matches = [...before.matchAll(/=\s*(`|')/g)];
  return matches.length ? matches[matches.length - 1][1] : '`';
}

/**
 * Everything from the start of the stage list to the end of the payload string.
 * A delimiter only ends the block when what follows it closes the statement,
 * which is what separates the closing quote from an apostrophe inside a
 * sentence. A delimiter followed by "+" does not end anything: one scenario
 * builds its paste by concatenating a quoted chunk per stage, so the block runs
 * through the glue between those chunks to the semicolon that ends the whole
 * expression.
 */
function stageBlockEnd(src, from, delim) {
  for (let i = from; i < src.length; i++) {
    if (src[i] !== delim || src[i - 1] === '\\') continue;
    const rest = src.slice(i + 1).match(/^\s*(.)/);
    if (rest && ';,)'.includes(rest[1])) return i;
  }
  return -1;
}

function extract(block, re, delim) {
  const m = block.match(re);
  if (!m) return '';
  return m[1]
    .split(delim)[0]
    .replace(/\\n[\s\S]*$/, '')
    .trim()
    .replace(/[.\s]+$/, '');
}

/**
 * Several step-out-of-character questions are questions, and one is two of them.
 * extract() strips a trailing period so the fragment can be re-punctuated, but a
 * fragment already ending in ? or ! is finished, and appending a period to it
 * produces "consequences (KC-6.3.I.A.ii)?." in a student's paste.
 */
function terminate(text) {
  return /[.?!]$/.test(text) ? text : `${text}.`;
}

function buildClosing(revisionTarget, reflection, nl) {
  const lines = [];
  const first = [
    'Coach me on one thing: is my decision defensible given my role, my evidence,',
    'and the tradeoff I accepted? Name the weakest part of it and tell me what to revise.'
  ].join(' ');
  lines.push(revisionTarget ? `${first} I am aiming for a stronger ${terminate(revisionTarget)}` : `${first}`);
  lines.push('');
  lines.push(
    'After I revise once, tell me whether it holds. When it does, I will step out of '
    + `character and ${terminate(reflection)} That reflection is the box at the end of this scenario, `
    + 'and it is what reaches Canvas through Gather All My Work on the lesson page.'
  );
  lines.push('');
  lines.push('Give me one thing to work on at a time. Do not write my final answer for me.');
  return lines.join(nl);
}

const files = walk(ROOM, []);
let changed = 0;
let skippedGenerated = 0;
let alreadyDone = 0;
const problems = [];

for (const file of files) {
  const rel = path.relative(ROOT, file);
  let src = fs.readFileSync(file, 'utf8');

  if (src.includes(GENERATED_MARKER)) { skippedGenerated++; continue; }
  if (src.includes(NEW_MARKER)) { alreadyDone++; continue; }

  const hadHeader = OLD_HEADER.test(src);
  const stagesAt = src.search(STAGES_START);
  // match(), not test(): these carry /g, and test() on a /g regex advances
  // lastIndex, so the next file it is asked about starts mid-string and can be
  // told there is nothing to fix when there is.
  const hasBespoke = BESPOKE_FIXES.some(([re]) => src.match(re));
  if (!hadHeader && stagesAt === -1 && !hasBespoke) continue;

  let next = src;
  if (hadHeader) next = next.replace(new RegExp(OLD_HEADER, 'g'), NEW_HEADER);
  for (const [re, to] of BESPOKE_FIXES) next = next.replace(re, to);

  if (stagesAt !== -1) {
    const start = next.search(STAGES_START);
    const delim = payloadDelimiter(next, start);
    const end = stageBlockEnd(next, start, delim);
    if (end === -1) { problems.push(`${rel}: stage list has no terminator, left alone`); continue; }

    const block = next.slice(start, end);
    const nl = newlineFlavour(block);
    const revisionTarget = extract(block, /revise into a stronger ([^\n]*)/, delim);
    const reflection = extract(block, /step out of character and ([^\n]*)/, delim);

    if (!reflection) {
      problems.push(`${rel}: no step-out-of-character question found, left alone`);
      continue;
    }
    if (!revisionTarget) problems.push(`${rel}: no revision target in stage 5, closing written without one`);

    const closing = buildClosing(
      escapeForLiteral(revisionTarget, delim),
      escapeForLiteral(reflection, delim),
      nl
    );
    next = next.slice(0, start) + closing + next.slice(end);
  }

  if (next === src) continue;
  changed++;
  if (DRY) {
    console.log(`\n--- ${rel}`);
    const at = next.indexOf(NEW_MARKER);
    console.log(next.slice(at, at + 700).split(/\\n|\n/).join('\n'));
  } else {
    fs.writeFileSync(file, next);
    console.log(`rewrote ${rel}`);
  }
}

console.log(
  `\n${DRY ? 'would rewrite' : 'rewrote'} ${changed}; `
  + `${alreadyDone} already normalized; ${skippedGenerated} generated, owned by build-unit6/9.`
);
if (problems.length) {
  console.log('\nNeeds a look:');
  for (const p of problems) console.log(`  ${p}`);
}
