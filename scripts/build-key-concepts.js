#!/usr/bin/env node
'use strict';

/*
 * Generate assets/data/key-concepts.js: every unit topic's College Board Key
 * Concepts, code and CED wording, for the Key Concept band on class slides.
 *
 *   node scripts/build-key-concepts.js            write the file
 *   node scripts/build-key-concepts.js --check    fail on drift, write nothing
 *
 * The first copy of a Key Concept is the topic's own lesson data file
 * (`collegeBoardKeyConcepts`). A slide names the code it teaches, `kc:
 * 'KC-3.1.IV'`, and never retypes the wording, because a second copy typed
 * into a deck is a second answer to "what does the CED say" with nothing able
 * to tell you which one the room read.
 *
 * The browser cannot read a lesson data file for this: those files touch the
 * DOM when they load, so a teacher page that loaded one to borrow its Key
 * Concepts would inherit the lesson page's side effects. So the wording is
 * lifted out here, through the same reader the Socrates Kit uses, into a
 * plain data file every deck can load. Keyed by topic, not by code, because
 * a few codes carry different wording on different topics today, and the
 * band must show the wording that topic's lesson shows.
 */

const fs = require('fs');
const path = require('path');
const vm = require('vm');
const { loadCourse } = require('./lib/socrates-course');

const ROOT = path.join(__dirname, '..');
const OUT = 'assets/data/key-concepts.js';

// A KC in the lesson data may carry a <br>-separated bullet list. The band is
// one or two lines of plain text, so the list is folded into the sentence.
const plain = s => String(s == null ? '' : s)
  .replace(/<br\s*\/?>\s*▪?\s*/gi, ' ▪ ')
  .replace(/<[^>]+>/g, '')
  .replace(/\s+/g, ' ')
  .trim();

function build() {
  const course = loadCourse();
  const topics = (course.topics || course).filter(t => t.kind === 'unit' && t.kcs && t.kcs.length);
  topics.sort((a, b) => a.sort[0] - b.sort[0] || a.sort[1] - b.sort[1]);
  const out = {};
  for (const t of topics) {
    out[t.id] = t.kcs.map(k => ({ code: plain(k.code), text: plain(k.text) })).filter(k => k.code && k.text);
  }
  return out;
}

function serialize(data) {
  return '/* GENERATED by scripts/build-key-concepts.js from each lesson\'s collegeBoardKeyConcepts. Do not hand-edit. */\n'
    + `window.BEHISTORICAL_KEY_CONCEPTS = ${JSON.stringify(data, null, 2)};\n`;
}

function main() {
  const check = process.argv.includes('--check');
  const want = serialize(build());
  const file = path.join(ROOT, OUT);
  if (check) {
    const have = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
    if (have !== want) {
      console.log(`DRIFT  ${OUT} does not match the lesson data. Run node scripts/build-key-concepts.js`);
      process.exit(1);
    }
    const sandbox = { window: {} };
    vm.createContext(sandbox);
    vm.runInContext(have, sandbox);
    console.log(`ok  ${OUT}, ${Object.keys(sandbox.window.BEHISTORICAL_KEY_CONCEPTS).length} topics`);
    return;
  }
  fs.writeFileSync(file, want);
  console.log(`wrote  ${OUT}`);
}

module.exports = { build, OUT };
if (require.main === module) main();
