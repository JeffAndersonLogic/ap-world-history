#!/usr/bin/env node
'use strict';

/**
 * Write assets/data/ebook-audio.js, the list of recorded eBook narrations the
 * Listen player reads.
 *
 *   node scripts/build-ebook-audio.js            write it, and report coverage
 *   node scripts/build-ebook-audio.js --check    fail on drift, write nothing
 *
 * The source is scripts/audio/recordings.json, which the narration generator
 * (scripts/audio/narrate.py) appends to as it records sections. Each entry is
 * keyed by the content fingerprint (data-listen-hash) of the section it was
 * made from, so this file never has to know whether a recording is current:
 * the page in front of the student decides that, by carrying the fingerprint or
 * not. See "Recorded narration" in docs/claude/deep-readings-and-ebook.md.
 *
 * The MP3s themselves are not in this repository. They are in the
 * behistorical-audio repository and served from its own GitHub Pages site,
 * because the whole eBook is close to a gigabyte of audio and GitHub Pages caps
 * a site at one.
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SOURCE = path.join(ROOT, 'scripts', 'audio', 'recordings.json');
const OUTPUT = path.join(ROOT, 'assets', 'data', 'ebook-audio.js');

const HASH = /^[0-9a-f]{16}$/;
const FILE = /^ebook\/([a-z0-9-]+)\/([0-9a-f]{16})\.mp3$/;

/** Every problem with a recordings list, as sentences. Empty means valid. */
function problems(data) {
  const out = [];
  if (!data || typeof data !== 'object') return ['the recordings list is not an object'];
  if (typeof data.base !== 'string' || !/^https:\/\/[^\s"'<>]+\/$/.test(data.base)) {
    out.push('base must be an https URL ending in a slash');
  }
  if (!data.recordings || typeof data.recordings !== 'object') return out.concat('recordings must be an object');
  for (const [hash, rec] of Object.entries(data.recordings)) {
    if (!HASH.test(hash)) { out.push(`"${hash}" is not a section fingerprint`); continue; }
    const m = FILE.exec(rec && rec.file);
    if (!m) { out.push(`${hash}: file must look like ebook/<volume>/<fingerprint>.mp3`); continue; }
    if (m[2] !== hash) out.push(`${hash}: its file is named for a different fingerprint, ${m[2]}`);
    if (!(rec.seconds > 0)) out.push(`${hash}: seconds must be a positive number`);
    if (typeof rec.section !== 'string' || !rec.section) out.push(`${hash}: section id is missing`);
  }
  return out;
}

function render(data) {
  const recordings = {};
  for (const hash of Object.keys(data.recordings).sort()) {
    const r = data.recordings[hash];
    recordings[hash] = { file: r.file, seconds: r.seconds, section: r.section };
  }
  const manifest = { base: data.base, narrator: data.narrator || '', recordings };
  return (
    '/* GENERATED by scripts/build-ebook-audio.js from scripts/audio/recordings.json.\n' +
    ' * Do not edit by hand. Each recording is keyed by the content fingerprint of\n' +
    ' * the eBook section it was made from; assets/js/behistorical-listen.js plays\n' +
    ' * one only when the section on the page carries that exact fingerprint. */\n' +
    'window.BH_EBOOK_AUDIO = ' + JSON.stringify(manifest, null, 2) + ';\n'
  );
}

/** Current fingerprints on the built eBook pages: hash -> { volume, section }. */
function currentSections() {
  const dir = path.join(ROOT, 'ebook');
  const out = new Map();
  for (const file of fs.readdirSync(dir).filter(f => f.endsWith('.html'))) {
    const src = fs.readFileSync(path.join(dir, file), 'utf8');
    const re = /<section[^>]*\sid="([^"]+)"[^>]*\sdata-listen-hash="([0-9a-f]{16})"/g;
    let m;
    while ((m = re.exec(src))) out.set(m[2], { volume: file.replace(/\.html$/, ''), section: m[1] });
  }
  return out;
}

function main() {
  const check = process.argv.includes('--check');
  const data = JSON.parse(fs.readFileSync(SOURCE, 'utf8'));
  const bad = problems(data);
  if (bad.length) {
    console.error(`scripts/audio/recordings.json is not valid:\n  ${bad.join('\n  ')}`);
    process.exit(1);
  }
  const text = render(data);
  if (check) {
    const onDisk = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, 'utf8') : null;
    if (onDisk !== text) {
      console.error('assets/data/ebook-audio.js does not match scripts/audio/recordings.json. Run: node scripts/build-ebook-audio.js');
      process.exit(1);
    }
  } else {
    fs.writeFileSync(OUTPUT, text);
  }

  // Coverage is reported, never enforced: a section without a recording, or a
  // recording of text that has since changed, is read by the browser voice from
  // the current text, which is correct, just not recorded.
  const sections = currentSections();
  const hashes = Object.keys(data.recordings);
  const live = hashes.filter(h => sections.has(h)).length;
  console.log(`${check ? 'checked' : 'wrote'} assets/data/ebook-audio.js: ${live} of ${sections.size} sections recorded` +
    (hashes.length - live ? `, ${hashes.length - live} recording${hashes.length - live === 1 ? '' : 's'} of text that has since changed` : ''));
}

module.exports = { problems, render, currentSections };
if (require.main === module) main();
