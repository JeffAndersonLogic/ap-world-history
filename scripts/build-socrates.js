#!/usr/bin/env node
/**
 * build-socrates.js
 *
 * Generates the Socrates Kit under `docs/socrates/`, the three documents that
 * configure the course-wide MagicSchool AI coach:
 *
 *   socrates-instructions.md    paste into the MagicSchool instructions field
 *   socrates-course-spine.md    upload as the chatbot's one attachment
 *   socrates-paste-contract.md  the exact shape of the prompt a page sends
 *
 * WHY THIS SCRIPT EXISTS
 *
 * Socrates is one chatbot reached from all 77 topics. His instructions were
 * written for Unit 1, which means a student in Unit 7 today is coached by a bot
 * whose only stated content knowledge is c. 1200 to c. 1450.
 *
 * The obvious fix, pasting nine units of content into the instructions field or
 * attaching a hand-built knowledge pack, fails the way this repo has already
 * been burned once: it makes a second copy of content whose first copy is the
 * lesson data, and nothing can tell you when the two disagree. A teacher edits
 * `lesson-5-7-...js`, the site updates, and the coach keeps teaching last
 * term's version with every structural check still green.
 *
 * So the split is:
 *
 *   - the persona is hand-authored and unit-agnostic, in
 *     `scripts/lib/socrates-persona.js`;
 *   - everything topic-specific is GENERATED from the lesson files here.
 *
 * Rebuild after changing any lesson data, then re-paste and re-upload. `--check`
 * fails on drift without writing, which is what the offline suite runs, so a
 * hand-edit to a generated file fails the push instead of being quietly
 * reverted by the next rebuild.
 *
 * WHAT IT READS
 *
 * Nothing directly. `scripts/lib/socrates-course.js` reads the course and builds
 * the context block; this script only lays those out as documents. The three
 * callers that need to agree on the paste shape all go through that lib.
 *
 * Usage: node scripts/build-socrates.js [--check]
 */

'use strict';

const fs = require('fs');
const path = require('path');
const { loadCourse, contextBlock } = require("./lib/socrates-course");
const { PERSONA } = require('./lib/socrates-persona');

const ROOT = path.join(__dirname, '..');
const RENDERER = path.join(ROOT, 'assets', 'js', 'behistorical-topic-renderer-v1.js');
const OUT = path.join(ROOT, 'docs', 'socrates');
const CHECK = process.argv.includes('--check');

// ── Emit ─────────────────────────────────────────────────────────────────────

const GEN = '<!-- GENERATED by scripts/build-socrates.js, do not hand-edit. Rebuild: node scripts/build-socrates.js -->';

// The ten modules, read out of the renderer's own table rather than restated
// here, the way build-skills-map.js reads its slot ids. A student says "I'm stuck
// on my BeSurreal" and a coach that has never heard the word asks them to explain
// their own course back to it.
//
// This is course structure, not course content: it is identical in Foundations and
// in Unit 9, it changes only when the ten-module standard changes, and it names no
// history. That is why it can live in the instructions field without becoming a
// second copy of anything.
function moduleTable() {
  const src = fs.readFileSync(RENDERER, 'utf8');
  const rows = [];
  const re = /\{\s*id:\s*'([a-z0-9]+)',\s*label:[^,]*?'(Module \d+)'[^,]*,\s*title:\s*'([^']+)'/g;
  let m;
  while ((m = re.exec(src))) rows.push({ id: m[1], label: m[2], title: m[3].replace(/\\'/g, "'") });
  if (rows.length < 8) {
    problems.push(`only ${rows.length} modules parsed out of the renderer, the module table read is broken`);
  }
  // Checkpoint 2's label is a ternary, `L.beInTheRoom ? 'Module 10' : 'Module 09'`,
  // so a greedy match reads the no-simulation fallback and emits two Module 09
  // rows. Duplicate labels are the symptom, and they are worth failing on rather
  // than shipping a module list that miscounts itself.
  const dupes = rows.map(r => r.label).filter((l, i, a) => a.indexOf(l) !== i);
  if (dupes.length) {
    problems.push(`duplicate module labels parsed from the renderer: ${[...new Set(dupes)].join(', ')}`);
  }
  return rows;
}

const MODULE_PURPOSE = {
  map: 'locating the topic, so geography is not decoration',
  first10: 'the narrative reading, with three questions. Its answers are what reach Canvas from this module',
  contentdelivery: 'the lecture cards, read on the page rather than in a pop-out',
  besurreal: 'one concrete everyday detail, used to make the period feel inhabited',
  skill: 'practice on one AP historical thinking skill',
  checkpoint1: 'the first written checkpoint',
  evidence: 'reading images and sources as evidence',
  source: 'a primary source with interpretation questions',
  beintheroom: 'a role-play simulation. Work here does NOT reach Canvas',
  checkpoint2: 'the synthesis checkpoint'
};

function instructionsDoc(topics) {
  const byUnit = new Map();
  topics.forEach(t => {
    const k = t.kind === 'foundations' ? 'Foundations' : t.unit;
    if (!byUnit.has(k)) byUnit.set(k, []);
    byUnit.get(k).push(t);
  });
  // The index is the only course content in the instructions field: enough for
  // the coach to know a Topic 7.2 exists and roughly when it sits, not enough
  // to teach from. Teaching content is the attachment's job, and the specific
  // assignment is the paste's job.
  const index = [...byUnit.entries()].map(([unit, ts]) => {
    const span = ts.map(t => t.period).filter(Boolean)[0] || '';
    return `- **${unit}**${span ? ` (${span})` : ''}: `
      + ts.map(t => `${t.id} ${t.title.split(':')[0]}`).join('; ');
  }).join('\n');

  return [
    GEN,
    '',
    PERSONA.trim(),
    '',
    '## The course you are coaching',
    '',
    'This index tells you which topics exist and roughly when each sits. It is not',
    'enough to teach from, and it is not a substitute for the student\'s context',
    'block. Use it to recognise when a student names a topic, and to notice when',
    'their evidence belongs to a different one.',
    '',
    index,
    '',
    '## How a lesson is built',
    '',
    'Every topic, Foundations and unit alike, has the same ten modules in the same',
    'order. When a student names one, this is what they mean:',
    '',
    ...moduleTable().map(r => `- **${r.label}, ${r.title}**`
      + (MODULE_PURPOSE[r.id] ? `: ${MODULE_PURPOSE[r.id]}.` : '.')),
    '',
    'You are reached from three of them: the First & 10 reading, both checkpoints, and',
    'BeInTheRoom. The AP historical thinking skills a student may name are',
    'contextualization, comparison, causation, continuity and change over time,',
    'sourcing, claims and evidence, and argumentation.',
    '',
    'Your attachment, the BeHistorical course spine, carries each topic\'s College',
    'Board key concepts, expected evidence terms, and checkpoint prompts. Consult it',
    'when a student asks something the context block does not cover. Prefer the',
    'context block, then the spine, then your own memory, in that order.',
    ''
  ].join('\n');
}

function spineEntry(t) {
  const lines = [`## ${t.id} ${t.title}`, ''];
  lines.push(`**Where this sits.** ${t.unit}${t.span ? `, ${t.span}` : ''}.`
    + (t.period ? ` ${t.period}` : ''), '');
  if (t.kcs.length) {
    lines.push('**College Board key concepts.**');
    t.kcs.forEach(k => lines.push(`- ${k.code}${k.theme ? ` (${k.theme})` : ''}: ${k.text}`
      + (k.examples.length ? ` Illustrative examples: ${k.examples.join(', ')}.` : '')));
    lines.push('');
  }
  // No learning targets and no success criteria here on purpose. Those reach the
  // coach in the student's paste, where they are scoped to the one module being
  // coached, and repeating all 77 topics' worth of them in the attachment buys a
  // second copy of the same sentences at a third again the page count.
  if (t.terms.length) lines.push(`**Expected evidence terms.** ${t.terms.join(', ')}.`, '');
  if (t.skill) lines.push(`**AP skill focus.** ${t.skill}.`, '');
  t.checkpoints.forEach(c => {
    lines.push(`**${c.label || 'Checkpoint'} prompt.** ${c.prompt}`);
    if (c.focus.length) lines.push(`Strong answer checklist: ${c.focus.join(' ')}`);
    lines.push('');
  });
  return lines.join('\n').trimEnd();
}

const SPINE_PREAMBLE = [
  '',
  'Reference for Socrates, the BeHistorical AI coach. One entry per topic, in',
  'course order. Each entry carries where the topic sits, its College Board key',
  'concepts, the evidence terms the teacher expects, the AP skill focus, and the',
  'checkpoint prompts students are answering.',
  '',
  'Generated from the course\'s own lesson files, so it agrees with what students',
  'see on the page. It deliberately carries no lecture content and no reading',
  'prose: a coach that recites the lesson is not coaching.',
  '',
  'When a student\'s pasted context block disagrees with this document, the block',
  'wins. The block came from the lesson they are actually sitting in.',
  ''
];

function spineDoc(topics) {
  return [GEN, '', '# BeHistorical Course Spine', ...SPINE_PREAMBLE,
    topics.map(spineEntry).join('\n\n'), ''].join('\n');
}

// Per-unit spines as well as the whole thing. Two reasons, and the second is the
// one that matters: an upload limit is a vendor detail nobody here can test
// against, so the fallback has to exist before it is needed; and a retrieval
// system asked for "Topic 6.4" over ten small documents makes a more precise
// choice than over one document of 119 pages.
function unitSpineDocs(topics) {
  const groups = new Map();
  topics.forEach(t => {
    const key = t.kind === 'foundations' ? 'foundations' : `unit-${t.id.split('.')[0]}`;
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key).push(t);
  });
  const out = {};
  for (const [key, ts] of groups) {
    out[`spine/socrates-spine-${key}.md`] = [
      GEN, '', `# BeHistorical Course Spine, ${ts[0].unit}`, ...SPINE_PREAMBLE,
      ts.map(spineEntry).join('\n\n'), ''
    ].join('\n');
  }
  return out;
}

function contractDoc(topics) {
  // The sample comes out of contextBlock(), the same function the eval sends to a
  // model, so this document cannot describe a shape the code does not produce.
  const sample = topics.find(t => t.id === '7.2') || topics.find(t => t.kind === 'unit');
  const block = contextBlock(sample, { draft: '<the student\'s draft, verbatim>' });

  return [
    GEN,
    '',
    '# The Socrates paste contract',
    '',
    'Socrates gets his topic knowledge from the student\'s pasted message, not from',
    'his own instructions. This file is the shape of that message.',
    '',
    'There is exactly one implementation of it,',
    '`assets/js/behistorical-coach-prompt.js`, reached four ways:',
    '',
    '1. the persona in `scripts/lib/socrates-persona.js` describes it, under',
    '   "Reading the paste";',
    '2. `generateCheckpointPrompt()` in `assets/js/behistorical-topic-renderer-v1.js`',
    '   calls it, from a copy inlined by `scripts/build-coach-prompt.js`;',
    '3. the 77 generated First & 10 readings call it, from a copy that',
    '   `scripts/lib/first10-page.js` emits into each page;',
    '4. `scripts/lib/socrates-course.js` calls it to produce this document and to',
    '   feed the graded eval.',
    '',
    'Three checks hold that together: `build-coach-prompt.js --check` re-derives the',
    'renderer\'s inlined copy and fails on drift, `scripts/test/coach-prompt.test.js`',
    'drives a real lesson page in Chromium and asserts the built paste is',
    'byte-identical to what this document specifies, and',
    '`scripts/test/socrates-contract.test.js` asserts all 77 topics can produce a',
    'complete block.',
    '',
    'Every field below is read off the lesson data at build time, so a teacher who',
    'edits a checkpoint prompt changes what the coach is told, with no second copy',
    'to remember to update.',
    '',
    '## The block',
    '',
    '```',
    block,
    '```',
    '',
    '## Why each line is there',
    '',
    '- **Topic, module, title.** Without these the coach has no idea which of 77',
    '  assignments it is looking at, and defaults to whatever its instructions',
    '  happened to name. This is the line that makes one bot work for nine units.',
    '- **Period.** The cheapest possible guard against a coach nodding along to an',
    '  anachronism.',
    '- **Learning target and success criteria.** What "good" means for this task, in',
    '  the teacher\'s words rather than the model\'s idea of AP writing.',
    '- **Key concept.** The CED language the answer is graded against.',
    '- **Focus terms.** Lets the coach ask for the specific evidence the teacher',
    '  expects instead of a generic "add more detail."',
    '- **Checklist.** The same three expectations the student can already see on the',
    '  page, so coach and page cannot contradict each other.',
    '- **Assigned prompt.** The coach needs the question, not just the answer.',
    '',
    '## The reading variant',
    '',
    'A First & 10 reading sends the same header lines and differs only below them,',
    'because a reading is three questions rather than one prompt:',
    '',
    '```',
    'Topic 7.2, First & 10 Reading, Causes of World War I.',
    '... the same Period, Lesson focus, Learning target, Success criteria,',
    '... Key concept and Focus terms lines ...',
    '',
    'Here are my responses:',
    '',
    'Question 1: <the question, read off the page>',
    'My response: <what the student typed>',
    '',
    'Question 2: ...',
    '',
    'Coach me by asking one question at a time. Do not write my final answer for me.',
    '```',
    '',
    'It carries no assigned prompt and no checklist, because a reading has neither.',
    'Pairing each answer with its question is the point: three loose paragraphs give',
    'the coach no way to tell which one was meant to be about causation.',
    ''
  ].join('\n');
}

// ── Write or check ───────────────────────────────────────────────────────────

const { topics, problems } = loadCourse();

if (!topics.length) problems.push('no topics resolved at all, the lesson data read is broken');

const files = Object.assign({
  'socrates-instructions.md': instructionsDoc(topics),
  'socrates-course-spine.md': spineDoc(topics),
  'socrates-paste-contract.md': contractDoc(topics)
}, unitSpineDocs(topics));

let drift = 0;
fs.mkdirSync(path.join(OUT, 'spine'), { recursive: true });
for (const [name, body] of Object.entries(files)) {
  const dest = path.join(OUT, name);
  const before = fs.existsSync(dest) ? fs.readFileSync(dest, 'utf8') : null;
  if (CHECK) {
    if (before !== body) { drift++; console.error(`DRIFT ${path.relative(ROOT, dest)}`); }
  } else if (before !== body) {
    fs.writeFileSync(dest, body);
    console.log(`wrote ${path.relative(ROOT, dest)}`);
  }
}

const kb = n => (n / 1024).toFixed(0) + ' KB';
console.log(`\n${topics.length} topics`
  + ` | instructions ${kb(files['socrates-instructions.md'].length)}`
  + ` | spine ${kb(files['socrates-course-spine.md'].length)}`
  + ` (~${Math.round(files['socrates-course-spine.md'].length / 1800)} pages)`);

if (problems.length) {
  console.error(`\n${problems.length} problem(s):`);
  problems.forEach(p => console.error('  ' + p));
}
if (CHECK && drift) {
  console.error(`\n${drift} file(s) drifted. Run: node scripts/build-socrates.js`);
  process.exit(1);
}
if (problems.length) process.exit(1);
